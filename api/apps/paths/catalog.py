def seed(apps=None):
    """Idempotent: creates missing rows, never overwrites admin edits."""
    if apps is None:
        from apps.paths.models import CareerPath, CuratedPath, Skill
    else:
        Skill, CuratedPath, CareerPath = (
            apps.get_model("paths", n) for n in ("Skill", "CuratedPath", "CareerPath")
        )
    for slug, name, ta, cat, kw in SKILLS:
        Skill.objects.get_or_create(
            slug=slug, defaults={"name": name, "name_ta": ta, "category": cat, "keywords": kw}
        )
    for slug, title, ta, emoji, level, desc, steps in PATHS:
        p, created = CuratedPath.objects.get_or_create(
            slug=slug,
            defaults={
                "title": title,
                "title_ta": ta,
                "emoji": emoji,
                "level": level,
                "description": desc,
                "steps": [{"title": t, "goal": g, "skill": s} for t, g, s in steps],
            },
        )
        if created:
            p.skills.set(Skill.objects.filter(slug__in=[s for _, _, s in steps]))
    for slug, title, ta, emoji, summary, salary, outlook, path_slug, reqs in CAREERS:
        CareerPath.objects.get_or_create(
            slug=slug,
            defaults={
                "title": title,
                "title_ta": ta,
                "emoji": emoji,
                "summary": summary,
                "salary_band": salary,
                "outlook": outlook,
                "requirements": [{"skill": s, "level": lv} for s, lv in reqs],
                "path": CuratedPath.objects.filter(slug=path_slug).first() if path_slug else None,
            },
        )
    if not any(f.name == "seniority" for f in CareerPath._meta.get_fields()):
        return  # an older migration state (0002) runs before the ladder fields exist; 0004 seeds them
    for slug, title, ta, emoji, summary, salary, outlook, path_slug, reqs, seniority in SENIOR_CAREERS:
        CareerPath.objects.get_or_create(
            slug=slug,
            defaults={
                "title": title,
                "title_ta": ta,
                "emoji": emoji,
                "summary": summary,
                "salary_band": salary,
                "outlook": outlook,
                "requirements": [{"skill": s, "level": lv} for s, lv in reqs],
                "seniority": seniority,
                "path": CuratedPath.objects.filter(slug=path_slug).first() if path_slug else None,
            },
        )
    for slug, (seniority, nxt, senior) in LADDER.items():  # only fill links an admin hasn't set
        CareerPath.objects.filter(slug=slug, next_roles=[], senior_roles=[]).update(
            seniority=seniority, next_roles=nxt, senior_roles=senior
        )
