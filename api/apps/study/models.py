class LessonTranslation(models.Model):
    """One shared, cached translation of a lesson (explanation, key points, activity payloads).
    Answer keys stay in the original; `maps` translate text answers back for grading."""

    class Status(models.TextChoices):
        TRANSLATING = "translating"
        READY = "ready"
        FAILED = "failed"

    subsection = models.ForeignKey(
        "learning.Subsection", on_delete=models.CASCADE, related_name="translations"
    )
    lang = models.CharField(max_length=4)
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.TRANSLATING)
    source_hash = models.CharField(max_length=64)  # re-translate if the lesson was edited
    title = models.CharField(max_length=300, blank=True)
    objective = models.TextField(blank=True)
    explanation_md = models.TextField(blank=True)
    key_points = models.JSONField(default=list)
    activities = models.JSONField(default=dict)  # {activity_id: {payload, explanation, accept, back}}
    error = models.CharField(max_length=300, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=["subsection", "lang"], name="uniq_lesson_translation")]


class ActivityHint(models.Model):
    """Cached hint text per (activity, level, language, companion character) — shared by every learner with that
    character. Generated from the character's default name and persona only, never a learner's own free-text name."""

    activity = models.ForeignKey("learning.Activity", on_delete=models.CASCADE, related_name="hints")
    level = models.PositiveSmallIntegerField()  # 1 nudge, 2 hint, 3 worked example
    lang = models.CharField(max_length=12)
    persona = models.CharField(max_length=12, default="kili")  # kili | mayil | yaanai
    text = models.TextField()
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["activity", "level", "lang", "persona"], name="uniq_activity_hint_persona"
            )
        ]


class HintUse(models.Model):
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="hint_uses")
    activity = models.ForeignKey("learning.Activity", on_delete=models.CASCADE, related_name="hint_uses")
    level = models.PositiveSmallIntegerField()
    cost = models.PositiveSmallIntegerField(default=0)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=["user", "activity", "level"], name="uniq_hint_use")]


class DailyRevision(models.Model):
    """Today's revision stations for one learner (regenerated each day; swaps are remembered)."""

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="daily_revisions"
    )
    day = models.DateField()
    focus = models.CharField(max_length=60, blank=True)  # skill slug theme, "" = mixed
    stations = models.JSONField(default=list)
    done = models.JSONField(default=list)  # station keys completed
    swaps = models.PositiveSmallIntegerField(default=0)
    circuits = models.PositiveSmallIntegerField(
        default=1
    )  # "one more circuit" adds a fresh round after finishing

    class Meta:
        constraints = [models.UniqueConstraint(fields=["user", "day"], name="uniq_daily_revision")]


class StudyBlock(models.Model):
    class Status(models.TextChoices):
        PLANNED = "planned"
        DONE = "done"
        SKIPPED = "skipped"

    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="study_blocks")
    date = models.DateField(db_index=True)
    start = models.CharField(max_length=5, default="19:00")  # HH:MM local
    minutes = models.PositiveSmallIntegerField(default=15)
    kind = models.CharField(max_length=12, default="lesson")  # lesson | review | practice | today | custom
    title = models.CharField(max_length=200)
    link = models.CharField(max_length=200, blank=True)
    status = models.CharField(max_length=8, choices=Status.choices, default=Status.PLANNED)
    moved_from = models.DateField(null=True, blank=True)
    auto = models.BooleanField(default=True)  # generated by the planner (vs added by the learner)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["date", "start", "id"]


class StudyPause(models.Model):
    """Away mode: streak protected and reminders muted between start and end (inclusive)."""

    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="study_pauses")
    start = models.DateField()
    end = models.DateField()
    reason = models.CharField(max_length=24, default="away")  # away | exams | festival | sick | other
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-start"]


def _buddy_token():
    return secrets.token_urlsafe(18)


class StudyBuddy(models.Model):
    """A mutual plan-sharing link between two learners (invite → accept)."""

    inviter = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="buddy_invites"
    )
    buddy = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.CASCADE, related_name="buddy_of"
    )
    email = models.EmailField(blank=True)
    token = models.CharField(max_length=32, unique=True, default=_buddy_token)
    accepted_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)


