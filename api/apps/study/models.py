class ExplainerVideo(models.Model):
    """AI explainer for one lesson + language: a scene-by-scene script (visual, key points, narration) that the
    player animates in sync with narration. Shared and cached like translations; rebuilt when the lesson changes."""

    class Status(models.TextChoices):
        GENERATING = "generating"
        READY = "ready"
        FAILED = "failed"

    subsection = models.ForeignKey("learning.Subsection", on_delete=models.CASCADE, related_name="explainers")
    lang = models.CharField(max_length=10)
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.GENERATING)
    source_hash = models.CharField(max_length=64)
    title = models.CharField(max_length=200, blank=True)
    scenes = models.JSONField(default=list)  # [{heading, points[], visual, narration}]
    error = models.CharField(max_length=300, blank=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=["subsection", "lang"], name="uniq_explainer")]


class PulseCheck(models.Model):
    """Mid-lesson check-in: how the pace, difficulty and energy feel, and whether the lesson covers what they wanted."""

    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="pulse_checks")
    subsection = models.ForeignKey(
        "learning.Subsection", on_delete=models.CASCADE, related_name="pulse_checks"
    )
    pace = models.CharField(max_length=6, blank=True)  # slow | ok | fast
    difficulty = models.CharField(max_length=6, blank=True)  # easy | right | hard
    energy = models.CharField(max_length=6, blank=True)  # low | ok | high
    relevant = models.BooleanField(null=True)
    wish = models.CharField(max_length=300, blank=True)  # "what I hoped this lesson would cover"
    created_at = models.DateTimeField(auto_now_add=True)


