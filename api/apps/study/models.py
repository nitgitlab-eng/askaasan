class PodcastEpisode(models.Model):
    """AI two-host podcast for one lesson + language: host A (curious learner) and host B (friendly expert) talk the
    lesson through. Shared and cached like explainer videos; rebuilt when the lesson changes."""

    subsection = models.ForeignKey("learning.Subsection", on_delete=models.CASCADE, related_name="podcasts")
    lang = models.CharField(max_length=10)
    status = models.CharField(max_length=12, default="generating")  # generating | ready | failed
    source_hash = models.CharField(max_length=64)
    title = models.CharField(max_length=200, blank=True)
    hosts = models.JSONField(default=dict)  # {"A": "Meera", "B": "Arjun"}
    turns = models.JSONField(default=list)  # [{speaker: "A"|"B", text}]
    error = models.CharField(max_length=300, blank=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=["subsection", "lang"], name="uniq_podcast")]


