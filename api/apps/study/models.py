class CourseCheckpoint(models.Model):
    """One shared question set per course, used for the pre-test (before) and post-test (after) to measure learning gain.
    Correct answers stay server-side until a test is submitted."""

    curriculum = models.OneToOneField(
        "learning.Curriculum", on_delete=models.CASCADE, related_name="checkpoint"
    )
    status = models.CharField(max_length=12, default="generating")  # generating | ready | failed
    items = models.JSONField(default=list)  # [{id, prompt, options[], correct[], explanation, lesson}]
    updated_at = models.DateTimeField(auto_now=True)


class CheckpointAttempt(models.Model):
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="checkpoint_attempts"
    )
    curriculum = models.ForeignKey(
        "learning.Curriculum", on_delete=models.CASCADE, related_name="checkpoint_attempts"
    )
    kind = models.CharField(max_length=4)  # pre | post
    answers = models.JSONField(default=dict)
    correct = models.PositiveSmallIntegerField(default=0)
    total = models.PositiveSmallIntegerField(default=0)
    confidence = models.JSONField(default=dict)  # {qid: 1..3} optional "how sure"
    created_at = models.DateTimeField(auto_now_add=True)

    @property
    def score(self) -> float:
        return round(self.correct / self.total, 3) if self.total else 0.0


